import { describe, it, expect, beforeEach } from "vitest";
import { dirname } from "node:path";
import CppEntryPointScanner from "../CppEntryPointScanner";
import IFileSystem from "../../../types/IFileSystem";
import TestFileSystem from "../../../types/__testUtils__/TestFileSystem";

/** A discovered .cnx file searched along its own directory, then the project. */
const alongProject = (cnxPath: string): readonly string[] => [
  dirname(cnxPath),
  "/project",
];

describe("CppEntryPointScanner", () => {
  let mockFs: IFileSystem;
  let files: Map<string, string>;

  beforeEach(() => {
    files = new Map();
    mockFs = TestFileSystem.with({
      readFile: (path: string) => {
        const content = files.get(path);
        if (!content) throw new Error(`File not found: ${path}`);
        return content;
      },
      exists: (path: string) => files.has(path),
      isDirectory: () => false,
      isFile: (path: string) => files.has(path),
      readdir: () => [],
      stat: () => ({ mtimeMs: Date.now() }),
    });
  });

  describe("scan", () => {
    it("should find .cnx source from header with marker", () => {
      files.set("/project/main.cpp", '#include "led.h"\nint main() {}');
      files.set(
        "/project/led.h",
        `/**
 * generated by cnx from: led.cnx
 */
void led_on(void);`,
      );
      files.set("/project/led.cnx", "scope LED { public void on() {} }");

      const scanner = new CppEntryPointScanner(
        ["/project"],
        mockFs,
        alongProject,
      );
      const result = scanner.scan("/project/main.cpp");

      expect(result.cnxSources).toHaveLength(1);
      expect(result.cnxSources[0]).toBe("/project/led.cnx");
    });

    it("should return empty when no cnx markers found", () => {
      files.set("/project/main.cpp", '#include "utils.h"\nint main() {}');
      files.set("/project/utils.h", "void utils_init(void);");

      const scanner = new CppEntryPointScanner(
        ["/project"],
        mockFs,
        alongProject,
      );
      const result = scanner.scan("/project/main.cpp");

      expect(result.cnxSources).toHaveLength(0);
      expect(result.noCnxFound).toBe(true);
    });

    it("should follow transitive includes through .cnx sources", () => {
      files.set("/project/main.cpp", '#include "middleware.h"');
      files.set(
        "/project/middleware.h",
        `/**
 * generated by cnx from: middleware.cnx
 */`,
      );
      files.set("/project/middleware.cnx", '#include "led.h"');
      files.set(
        "/project/led.h",
        `/**
 * generated by cnx from: led.cnx
 */`,
      );
      files.set("/project/led.cnx", "scope LED {}");

      const scanner = new CppEntryPointScanner(
        ["/project"],
        mockFs,
        alongProject,
      );
      const result = scanner.scan("/project/main.cpp");

      expect(result.cnxSources).toContain("/project/middleware.cnx");
      expect(result.cnxSources).toContain("/project/led.cnx");
    });

    it("should report error when marker points to missing .cnx", () => {
      files.set("/project/main.cpp", '#include "led.h"');
      files.set(
        "/project/led.h",
        `/**
 * generated by cnx from: led.cnx
 */`,
      );
      // led.cnx does NOT exist

      const scanner = new CppEntryPointScanner(
        ["/project"],
        mockFs,
        alongProject,
      );
      const result = scanner.scan("/project/main.cpp");

      expect(result.errors).toHaveLength(1);
      expect(result.errors[0]).toMatchObject({
        sourcePath: "/project/led.h",
        line: 2,
        column: 26,
        message: "error[E0509]: cnx source not found: led.cnx",
        severity: "error",
      });
    });

    // #1833 ruling: only a lowercase `.cnx` is cnx source; #2167: `.cnext`,
    // in any case, is E0519.
    it.each([
      [
        "Led.CNX",
        "error[E0518]: cnx source extension must be lowercase: Led.CNX",
      ],
      [
        "Led.cnext",
        "error[E0519]: `.cnext` no longer names cnx source; rename it to `.cnx`: Led.cnext",
      ],
      ["Led.cnx", null],
    ])("a marker naming %s that exists: %s", (name, message) => {
      files.set("/project/main.cpp", '#include "led.h"');
      files.set(
        "/project/led.h",
        `/**
 * generated by cnx from: ${name}
 */`,
      );
      files.set(`/project/${name}`, "void blink() { }");

      const scanner = new CppEntryPointScanner(
        ["/project"],
        mockFs,
        alongProject,
      );
      const result = scanner.scan("/project/main.cpp");

      if (message === null) {
        expect(result.errors).toEqual([]);
        expect(result.cnxSources).toEqual([`/project/${name}`]);
        return;
      }
      expect(result.cnxSources).toEqual([]);
      expect(result.errors).toHaveLength(1);
      expect(result.errors[0]).toMatchObject({
        sourcePath: "/project/led.h",
        line: 2,
        column: 26,
        message,
        severity: "error",
      });
    });

    it("should handle cycle detection", () => {
      files.set("/project/main.cpp", '#include "a.h"');
      files.set(
        "/project/a.h",
        `/**
 * generated by cnx from: a.cnx
 */`,
      );
      files.set("/project/a.cnx", '#include "b.h"');
      files.set(
        "/project/b.h",
        `/**
 * generated by cnx from: b.cnx
 */`,
      );
      files.set("/project/b.cnx", '#include "a.h"'); // cycle back to a.h

      const scanner = new CppEntryPointScanner(
        ["/project"],
        mockFs,
        alongProject,
      );
      const result = scanner.scan("/project/main.cpp");

      // Should not infinite loop
      expect(result.cnxSources).toContain("/project/a.cnx");
      expect(result.cnxSources).toContain("/project/b.cnx");
    });

    it("should handle multiple includes in one file", () => {
      files.set(
        "/project/main.cpp",
        `#include "led.h"
#include "motor.h"
int main() {}`,
      );
      files.set(
        "/project/led.h",
        `/**
 * generated by cnx from: led.cnx
 */`,
      );
      files.set("/project/led.cnx", "scope LED {}");
      files.set(
        "/project/motor.h",
        `/**
 * generated by cnx from: motor.cnx
 */`,
      );
      files.set("/project/motor.cnx", "scope Motor {}");

      const scanner = new CppEntryPointScanner(
        ["/project"],
        mockFs,
        alongProject,
      );
      const result = scanner.scan("/project/main.cpp");

      expect(result.cnxSources).toHaveLength(2);
      expect(result.cnxSources).toContain("/project/led.cnx");
      expect(result.cnxSources).toContain("/project/motor.cnx");
    });

    it("should skip system includes", () => {
      files.set(
        "/project/main.cpp",
        `#include <stdio.h>
#include "led.h"
int main() {}`,
      );
      files.set(
        "/project/led.h",
        `/**
 * generated by cnx from: led.cnx
 */`,
      );
      files.set("/project/led.cnx", "scope LED {}");

      const scanner = new CppEntryPointScanner(
        ["/project"],
        mockFs,
        alongProject,
      );
      const result = scanner.scan("/project/main.cpp");

      // Should only find led.cnx, not fail on stdio.h
      expect(result.cnxSources).toHaveLength(1);
      expect(result.cnxSources[0]).toBe("/project/led.cnx");
    });

    it("should scan non-cnx headers for nested includes", () => {
      files.set("/project/main.cpp", '#include "wrapper.h"');
      files.set("/project/wrapper.h", '#include "led.h"\nvoid wrapper_init();');
      files.set(
        "/project/led.h",
        `/**
 * generated by cnx from: led.cnx
 */`,
      );
      files.set("/project/led.cnx", "scope LED {}");

      const scanner = new CppEntryPointScanner(
        ["/project"],
        mockFs,
        alongProject,
      );
      const result = scanner.scan("/project/main.cpp");

      expect(result.cnxSources).toHaveLength(1);
      expect(result.cnxSources[0]).toBe("/project/led.cnx");
    });

    it("should handle old-style cnx markers without source path", () => {
      files.set("/project/main.cpp", '#include "led.h"');
      files.set(
        "/project/led.h",
        `/**
 * generated by cnx
 */
void led_on(void);`,
      );

      const scanner = new CppEntryPointScanner(
        ["/project"],
        mockFs,
        alongProject,
      );
      const result = scanner.scan("/project/main.cpp");

      // Old marker without source path - should be treated as cnx generated
      // but without a source path, we can't add it to cnxSources
      expect(result.cnxSources).toHaveLength(0);
      // Should not follow includes from old-style cnx headers (they're leaf nodes)
    });

    it("should find .cnx source via search paths when --header-out is used", () => {
      // Simulate --header-out: headers in include/, sources in src/
      files.set("/project/main.cpp", '#include "led.h"');
      files.set(
        "/project/include/led.h",
        `/**
 * generated by cnx from: led.cnx
 */
void led_on(void);`,
      );
      // Source is in src/, not include/
      files.set("/project/src/led.cnx", "scope LED { public void on() {} }");

      // Scanner search paths include src/
      const scanner = new CppEntryPointScanner(
        ["/project/include", "/project/src"],
        mockFs,
        alongProject,
      );
      const result = scanner.scan("/project/main.cpp");

      expect(result.cnxSources).toHaveLength(1);
      expect(result.cnxSources[0]).toBe("/project/src/led.cnx");
      expect(result.errors).toHaveLength(0);
    });

    it("searches a discovered .cnx file's includes along its own path (#1706)", () => {
      files.set("/project/main.cpp", '#include "a.h"');
      files.set("/project/a.h", "/**\n * generated by cnx from: a.cnx\n */");
      files.set("/project/a.cnx", '#include "other.h"\nvoid a() {}');
      // Reachable only along the search path a.cnx gets, as a library tier.
      files.set(
        "/lib/other.h",
        "/**\n * generated by cnx from: other.cnx\n */",
      );
      files.set("/lib/other.cnx", "void other() {}");

      const scanner = new CppEntryPointScanner(["/project"], mockFs, (cnx) => [
        dirname(cnx),
        "/lib",
      ]);
      const result = scanner.scan("/project/main.cpp");

      expect(result.cnxSources).toEqual(["/project/a.cnx", "/lib/other.cnx"]);
      expect(result.errors).toEqual([]);
    });
  });
});
