import { describe, it, expect } from "vitest";
import RegExpUtils from "../RegExpUtils";

describe("RegExpUtils.escape", () => {
  it.each([
    ".",
    "*",
    "+",
    "?",
    "^",
    "$",
    "{",
    "}",
    "(",
    ")",
    "|",
    "[",
    "]",
    "\\",
    "/",
  ])("makes %s match only itself", (char) => {
    const regex = new RegExp(`^a${RegExpUtils.escape(char)}b$`);
    expect(regex.test(`a${char}b`)).toBe(true);
    expect(regex.test("axb")).toBe(false);
  });

  it("leaves ordinary text as it is", () => {
    expect(RegExpUtils.escape("generated by cnx from:")).toBe(
      "generated by cnx from:",
    );
  });
});
