/**
 * #1745: 1.1 Discover and the parser agree on which lines of a `.cnx` file are
 * `#include` directives.
 *
 * Discovery found them with a text scanner that knew nothing about comments.
 * The parser finds them with the grammar's include token, and a comment is a
 * skipped token there. So discovery pulled in a file that a block comment had
 * disabled, and missed one written after a comment on its line.
 *
 * Case (a) lives here, not as a `.cnx` fixture, because the formatter moves a
 * comment that precedes a directive onto a line of its own, and the pre-commit
 * hook formats every staged `.cnx` file, so the shape could not survive a
 * commit. Here its bytes are written exactly.
 *
 * Case (b) is asserted on a run that SUCCEEDS: the commented-out include's
 * type is never used, so the run must discover exactly the entry. The
 * diagnostic half of (b) is the `.cnx` fixtures in
 * `tests/bugs/issue-1745-include-directive-agreement/`.
 *
 * (b) is asserted on every route that reads a `.cnx` file's includes: a
 * `.cnx` entry, a `.cnx` file a C/C++ entry point reaches, and the #985
 * recovery translation unit. The review of #1830 found the last two still
 * reading with comment-blind scans after the first was fixed.
 */

import { describe, it, expect, beforeEach, afterEach, vi } from "vitest";
import { mkdtempSync, mkdirSync, writeFileSync, rmSync } from "node:fs";
import { execFileSync } from "node:child_process";
import { basename, dirname, join } from "node:path";
import { tmpdir } from "node:os";

import Transpiler from "../Transpiler";
import NodeFileSystem from "../../PARSE/1-Discover/NodeFileSystem";
import ExternalDeclarationOracle from "../../PARSE/1-Discover/preprocessor/ExternalDeclarationOracle";

const COLORS = "enum EColor {\n    RED,\n    GREEN\n}\n";
const GHOST = "enum EGhost {\n    A,\n    B\n}\n";

const USES_COLOR =
  "i32 main() {\n" +
  "    EColor c <- EColor.GREEN;\n" +
  "    if (c != EColor.GREEN) {\n" +
  "        return 1;\n" +
  "    }\n" +
  "    return 0;\n" +
  "}\n";

const USES_NOTHING = "i32 main() {\n    return 0;\n}\n";

const ANSWER = "i32 answer() {\n    return 42;\n}\n";

/** A header the transpiler generated from `source`, as its marker says. */
function generatedHeader(source: string, guard: string): string {
  return (
    `/**\n * Generated by C-Next Transpiler from: ${source}\n */\n` +
    `#ifndef ${guard}\n#define ${guard}\n#endif\n`
  );
}

describe("1.1 Discover and the parser agree on a file's includes (#1745)", () => {
  let project: string;

  beforeEach(() => {
    project = mkdtempSync(join(tmpdir(), "cnext-1745-"));
  });

  afterEach(() => {
    rmSync(project, { recursive: true, force: true });
  });

  /** Write `files` into the project, then transpile from `entry`. */
  async function transpileEntry(entry: string, files: Record<string, string>) {
    for (const [name, text] of Object.entries(files)) {
      mkdirSync(dirname(join(project, name)), { recursive: true });
      writeFileSync(join(project, name), text);
    }
    return new Transpiler(
      {
        target: "host",
        input: join(project, entry),
        outDir: join(project, "build"),
        noCache: true,
      },
      NodeFileSystem.instance,
    ).transpile({ kind: "files" });
  }

  /** Transpile `main.cnx`, holding `source`, beside the given helpers. */
  function transpileMain(source: string, helpers: Record<string, string>) {
    return transpileEntry("main.cnx", { ...helpers, "main.cnx": source });
  }

  type TResult = Awaited<ReturnType<typeof transpileEntry>>;

  /** The source files the run discovered, by name. */
  function discovered(result: TResult) {
    return result.files.map((f) => basename(f.sourcePath)).sort();
  }

  /** Compile every generated `.c` against the generated headers, -Werror. */
  function compiles(result: TResult): void {
    const out = join(project, "compiled");
    mkdirSync(out);
    for (const file of result.files) {
      const stem = basename(file.sourcePath).replace(/\.cnx$/, "");
      writeFileSync(join(out, `${stem}.c`), file.code);
      writeFileSync(join(out, `${stem}.h`), file.headerCode ?? "");
    }
    for (const file of result.files) {
      const stem = basename(file.sourcePath).replace(/\.cnx$/, "");
      execFileSync("gcc", [
        "-std=c99",
        "-Werror",
        "-c",
        "-I",
        out,
        join(out, `${stem}.c`),
        "-o",
        join(out, `${stem}.o`),
      ]);
    }
  }

  describe("(a) a directive after a comment on its line", () => {
    it("is discovered, and the program compiles", async () => {
      const result = await transpileMain(
        `/* driver */ #include "colors.cnx"\n\n${USES_COLOR}`,
        { "colors.cnx": COLORS },
      );

      expect(result.errors).toEqual([]);
      expect(discovered(result)).toEqual(["colors.cnx", "main.cnx"]);
      expect(() => compiles(result)).not.toThrow();
    });

    it("control: the same directive on its own line", async () => {
      const result = await transpileMain(
        `/* driver */\n#include "colors.cnx"\n\n${USES_COLOR}`,
        { "colors.cnx": COLORS },
      );

      expect(result.errors).toEqual([]);
      expect(discovered(result)).toEqual(["colors.cnx", "main.cnx"]);
      expect(() => compiles(result)).not.toThrow();
    });
  });

  describe("(b) an include inside a block comment", () => {
    it("pulls nothing into the run", async () => {
      const result = await transpileMain(
        `/*\n#include "ghost.cnx"\n*/\n\n${USES_NOTHING}`,
        { "ghost.cnx": GHOST },
      );

      expect(result.errors).toEqual([]);
      expect(discovered(result)).toEqual(["main.cnx"]);
    });

    it("control: the same include as a directive is discovered", async () => {
      const result = await transpileMain(
        `#include "ghost.cnx"\n\n${USES_NOTHING}`,
        { "ghost.cnx": GHOST },
      );

      expect(result.errors).toEqual([]);
      expect(discovered(result)).toEqual(["ghost.cnx", "main.cnx"]);
    });
  });

  describe("(b) in a .cnx file a C/C++ entry point reaches", () => {
    /**
     * main.cpp reaches app.cnx through its header, and inc/ghost.h names
     * ghost.cnx. The header sits apart from its source, as `--header-out`
     * writes it: beside its source, a real include of it is E0504.
     */
    function fromMainCpp(appSource: string) {
      return transpileEntry("main.cpp", {
        "ghost.cnx": GHOST,
        "inc/ghost.h": generatedHeader("ghost.cnx", "GHOST_H"),
        "app.cnx": appSource,
        "app.h": generatedHeader("app.cnx", "APP_H"),
        "main.cpp": '#include "app.h"\n\nint main() { return 0; }\n',
      });
    }

    it("pulls nothing into the run", async () => {
      const result = await fromMainCpp(
        `/*\n#include "inc/ghost.h"\n*/\n\n${ANSWER}`,
      );

      expect(result.errors).toEqual([]);
      expect(discovered(result)).toEqual(["app.cnx"]);
    });

    it("control: the same include as a directive is discovered", async () => {
      const result = await fromMainCpp(`#include "inc/ghost.h"\n\n${ANSWER}`);

      expect(result.errors).toEqual([]);
      expect(discovered(result)).toEqual(["app.cnx", "ghost.cnx"]);
    });
  });

  describe("(b) in the #985 recovery translation unit", () => {
    // A header whose own preprocessing fails sends every C include of every
    // .cnx file through one recovered translation unit, whose declarations
    // join the symbol table. broken.h needs prior.h first; sinker.h, which
    // refuses to follow prior.h, sinks the retry with the headers before it,
    // and the unit drops sinker.h and settles broken.h (#1844).
    const BROKEN =
      '#ifndef PRIOR_LEVEL\n#error "include prior first"\n#endif\n' +
      "#if PRIOR_LEVEL > 1\nvoid real_fn(void);\n#endif\n";
    const HELPERS = {
      "prior.h": "#define PRIOR_LEVEL 2\n",
      "sinker.h": '#ifdef PRIOR_LEVEL\n#error "include sinker first"\n#endif\n',
      "broken.h": BROKEN,
      "hidden.h": "void hidden_fn(void);\n",
    };
    const BROKEN_FIRST =
      '#include "prior.h"\n#include "sinker.h"\n#include "broken.h"\n';
    const CALLS_HIDDEN = "i32 main() {\n    hidden_fn();\n    return 0;\n}\n";

    it("takes no declaration from a block-commented header", async () => {
      const result = await transpileMain(
        `${BROKEN_FIRST}/*\n#include "hidden.h"\n*/\n\n${CALLS_HIDDEN}`,
        HELPERS,
      );

      expect(result.errors.map((e) => e.message).join("\n")).toContain(
        "error[E0422]: function 'hidden_fn' called before definition",
      );
    });

    it("is handed exactly the C includes the grammar reads", async () => {
      // The unit's own input, asserted directly. A `.cnext` include is C-Next
      // and stays out (the regex this replaced skipped `.cnx` only), an angle
      // include keeps its form, and `#include"tight.h"` is a directive the
      // grammar allows with no space, which the regex missed.
      const recover = vi.spyOn(ExternalDeclarationOracle, "recover");
      try {
        await transpileMain(
          BROKEN_FIRST +
            '#include <stdint.h>\n#include"tight.h"\n' +
            '#include "lib.cnext"\n/*\n#include "hidden.h"\n*/\n\n' +
            USES_NOTHING,
          {
            ...HELPERS,
            "tight.h": "void tight_fn(void);\n",
            "lib.cnext": "enum ELib {\n    X\n}\n",
          },
        );

        expect(recover).toHaveBeenCalledTimes(1);
        expect(recover.mock.calls[0][0]).toEqual([
          '"prior.h"',
          '"sinker.h"',
          '"broken.h"',
          "<stdint.h>",
          '"tight.h"',
        ]);
      } finally {
        recover.mockRestore();
      }
    });

    it("control: the same header as a directive declares it", async () => {
      const result = await transpileMain(
        `${BROKEN_FIRST}#include "hidden.h"\n\n${CALLS_HIDDEN}`,
        HELPERS,
      );

      expect(result.errors).toEqual([]);
    });
  });
});
